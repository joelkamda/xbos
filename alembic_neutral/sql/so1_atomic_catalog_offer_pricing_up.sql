    CONSTRAINT fk_so1_catalog_entries_unit FOREIGN KEY(tenant_id,atomic_unit_id) REFERENCES public.atomic_units(tenant_id,id) ON DELETE RESTRICT,
    CONSTRAINT fk_so1_catalog_entries_offer FOREIGN KEY(tenant_id,offer_id) REFERENCES public.so1_offers(tenant_id,id) ON DELETE RESTRICT,
