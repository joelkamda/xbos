CREATE TABLE public.so1_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(), tenant_id INTEGER NOT NULL,
    target_type VARCHAR(16) NOT NULL, atomic_unit_id INTEGER NULL, offer_id BIGINT NULL,
    price_code VARCHAR(80) NOT NULL, amount NUMERIC(18,6) NOT NULL, currency CHAR(3) NOT NULL,
    scope_type VARCHAR(24) NOT NULL, scope_id BIGINT NULL, precedence INTEGER NOT NULL DEFAULT 0,
    effective_from TIMESTAMPTZ NOT NULL, effective_to TIMESTAMPTZ NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), row_version INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT uq_so1_prices_public_id UNIQUE(public_id),
    CONSTRAINT fk_so1_prices_tenant FOREIGN KEY(tenant_id) REFERENCES public.tenants(id) ON DELETE RESTRICT,
    CONSTRAINT fk_so1_prices_unit FOREIGN KEY(tenant_id,atomic_unit_id) REFERENCES public.atomic_units(tenant_id,id) ON DELETE RESTRICT,
    CONSTRAINT fk_so1_prices_offer FOREIGN KEY(tenant_id,offer_id) REFERENCES public.so1_offers(tenant_id,id) ON DELETE RESTRICT,
    CONSTRAINT ck_so1_prices_target CHECK((target_type='atomic_unit' AND atomic_unit_id IS NOT NULL AND offer_id IS NULL) OR (target_type='offer' AND offer_id IS NOT NULL AND atomic_unit_id IS NULL)),
    CONSTRAINT ck_so1_prices_amount CHECK(amount>=0),
    CONSTRAINT ck_so1_prices_currency CHECK(currency=upper(currency) AND currency~'^[A-Z]{3}$'),
    CONSTRAINT ck_so1_prices_scope CHECK(scope_type IN ('tenant','legal_entity','organization_unit','location') AND ((scope_type='tenant' AND scope_id IS NULL) OR (scope_type<>'tenant' AND scope_id IS NOT NULL))),
    CONSTRAINT ck_so1_prices_window CHECK(effective_to IS NULL OR effective_to>effective_from),
    CONSTRAINT ck_so1_prices_code CHECK(price_code=btrim(price_code) AND length(price_code)>0),
    CONSTRAINT ck_so1_prices_version CHECK(row_version>=1)
);

