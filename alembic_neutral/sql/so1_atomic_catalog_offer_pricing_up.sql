CREATE TABLE public.so1_catalogs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(), tenant_id INTEGER NOT NULL,
    code VARCHAR(80) NOT NULL, name VARCHAR(200) NOT NULL,
    scope_type VARCHAR(24) NOT NULL, scope_id BIGINT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    effective_from TIMESTAMPTZ NOT NULL, effective_to TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), row_version INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT uq_so1_catalogs_public_id UNIQUE(public_id),
    CONSTRAINT uq_so1_catalogs_tenant_id_id UNIQUE(tenant_id,id),
    CONSTRAINT uq_so1_catalogs_tenant_code UNIQUE(tenant_id,code),
    CONSTRAINT fk_so1_catalogs_tenant FOREIGN KEY(tenant_id) REFERENCES public.tenants(id) ON DELETE RESTRICT,
    CONSTRAINT ck_so1_catalogs_scope CHECK(scope_type IN ('tenant','legal_entity','organization_unit','location') AND ((scope_type='tenant' AND scope_id IS NULL) OR (scope_type<>'tenant' AND scope_id IS NOT NULL))),
    CONSTRAINT ck_so1_catalogs_window CHECK(effective_to IS NULL OR effective_to>effective_from),
    CONSTRAINT ck_so1_catalogs_code CHECK(code=btrim(code) AND length(code)>0),
    CONSTRAINT ck_so1_catalogs_name CHECK(length(btrim(name))>0),
    CONSTRAINT ck_so1_catalogs_version CHECK(row_version>=1)
);

CREATE TABLE public.so1_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(), tenant_id INTEGER NOT NULL,
    code VARCHAR(80) NOT NULL, name VARCHAR(200) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), row_version INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT uq_so1_offers_public_id UNIQUE(public_id),
    CONSTRAINT uq_so1_offers_tenant_id_id UNIQUE(tenant_id,id),
    CONSTRAINT uq_so1_offers_tenant_code UNIQUE(tenant_id,code),
    CONSTRAINT fk_so1_offers_tenant FOREIGN KEY(tenant_id) REFERENCES public.tenants(id) ON DELETE RESTRICT,
    CONSTRAINT ck_so1_offers_code CHECK(code=btrim(code) AND length(code)>0),
    CONSTRAINT ck_so1_offers_name CHECK(length(btrim(name))>0),
    CONSTRAINT ck_so1_offers_metadata CHECK(jsonb_typeof(metadata)='object'),
    CONSTRAINT ck_so1_offers_version CHECK(row_version>=1)
);

