    CONSTRAINT fk_cc_order_draft_organization FOREIGN KEY(tenant_id,organization_unit_id)
        REFERENCES public.organization_units(tenant_id,id) ON DELETE RESTRICT,
    CONSTRAINT fk_cc_order_draft_location FOREIGN KEY(tenant_id,location_id)
        REFERENCES public.locations(tenant_id,id) ON DELETE RESTRICT,
    CONSTRAINT fk_cc_order_draft_merchant FOREIGN KEY(merchant_public_id)
        REFERENCES public.pa_merchants(public_id) ON DELETE RESTRICT,
    CONSTRAINT fk_cc_order_draft_context FOREIGN KEY(tenant_id,context_binding_public_id)
        REFERENCES public.ia0_interaction_context_bindings(tenant_id,public_id) ON DELETE RESTRICT,
    CONSTRAINT fk_cc_order_draft_catalog_binding FOREIGN KEY(tenant_id,catalog_binding_public_id)
        REFERENCES public.restaurant_customer_catalog_read_bindings(tenant_id,public_id) ON DELETE RESTRICT,
