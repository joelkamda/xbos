CREATE OR REPLACE FUNCTION public.cc_validate_order_draft_binding()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    binding public.restaurant_customer_catalog_read_bindings%ROWTYPE;
    order_row public.r1_restaurant_orders%ROWTYPE;
BEGIN
    SELECT * INTO binding
    FROM public.restaurant_customer_catalog_read_bindings
    WHERE tenant_id=NEW.tenant_id
      AND public_id=NEW.catalog_binding_public_id;

    IF NOT FOUND
       OR binding.merchant_public_id<>NEW.merchant_public_id
       OR binding.location_id<>NEW.location_id
       OR binding.row_version<>NEW.catalog_binding_version
       OR binding.active=false THEN
        RAISE EXCEPTION 'customer_channel_draft_catalog_binding_mismatch'
            USING ERRCODE='23514';
    END IF;

    SELECT * INTO order_row
    FROM public.r1_restaurant_orders
    WHERE tenant_id=NEW.tenant_id
      AND public_id=NEW.order_public_id;

    IF NOT FOUND OR order_row.source_channel_code<>'customer_channel' THEN
        RAISE EXCEPTION 'customer_channel_draft_order_mismatch'
            USING ERRCODE='23514';
    END IF;

    IF TG_OP='UPDATE' THEN
        NEW.updated_at := now();
    END IF;

    RETURN NEW;
END
$$;

CREATE TRIGGER trg_cc_order_draft_validate
BEFORE INSERT OR UPDATE
ON public.restaurant_customer_order_drafts
FOR EACH ROW
EXECUTE FUNCTION public.cc_validate_order_draft_binding();

CREATE OR REPLACE FUNCTION public.cc_validate_order_draft_line()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    draft_row public.restaurant_customer_order_drafts%ROWTYPE;
    line_order UUID;
    item_tenant BIGINT;
BEGIN
    SELECT * INTO draft_row
    FROM public.restaurant_customer_order_drafts
    WHERE tenant_id=NEW.tenant_id AND id=NEW.draft_id;

    SELECT o.public_id INTO line_order
    FROM public.r1_restaurant_order_lines l
    JOIN public.r1_restaurant_orders o
      ON (o.tenant_id,o.id)=(l.tenant_id,l.order_id)
    WHERE l.tenant_id=NEW.tenant_id
      AND l.public_id=NEW.order_line_public_id;

    SELECT tenant_id INTO item_tenant
    FROM public.so1_catalog_entries
    WHERE public_id=NEW.item_public_id;

    IF draft_row.id IS NULL
       OR line_order IS DISTINCT FROM draft_row.order_public_id
       OR item_tenant IS DISTINCT FROM NEW.tenant_id THEN
        RAISE EXCEPTION 'customer_channel_draft_line_binding_mismatch'
            USING ERRCODE='23514';
    END IF;

    RETURN NEW;
END
$$;

CREATE TRIGGER trg_cc_order_draft_line_validate
BEFORE INSERT OR UPDATE
ON public.restaurant_customer_order_draft_lines
FOR EACH ROW
EXECUTE FUNCTION public.cc_validate_order_draft_line();

