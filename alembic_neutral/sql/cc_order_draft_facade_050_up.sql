        REFERENCES public.ia0_interaction_context_bindings(tenant_id,public_id) ON DELETE RESTRICT,
    CONSTRAINT ck_cc_order_draft_catalog_binding_version CHECK(catalog_binding_version>=1),
    CONSTRAINT ck_cc_order_draft_mode CHECK(service_mode IN ('dine_in','takeaway','delivery')),
    CONSTRAINT ck_cc_order_draft_state CHECK(lifecycle_status IN ('open','submitted','cancelled')),
    CONSTRAINT ck_cc_order_draft_row_version CHECK(row_version>=1)
);

