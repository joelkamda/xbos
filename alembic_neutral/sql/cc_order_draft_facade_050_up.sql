    context_binding_public_id UUID NOT NULL,
    catalog_binding_public_id UUID NOT NULL,
    catalog_binding_version INTEGER NOT NULL,
    order_public_id UUID NOT NULL,
    service_mode VARCHAR(24) NOT NULL,
    table_resource_public_id UUID NULL,
    contact_binding_public_id UUID NULL,
    delivery_address_binding_public_id UUID NULL,
    lifecycle_status VARCHAR(16) NOT NULL DEFAULT 'open',
    row_version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_cc_order_draft_public UNIQUE(public_id),
    CONSTRAINT uq_cc_order_draft_tenant_public UNIQUE(tenant_id,public_id),
    CONSTRAINT uq_cc_order_draft_tenant_id UNIQUE(tenant_id,id),
    CONSTRAINT uq_cc_order_draft_order UNIQUE(tenant_id,order_public_id),
