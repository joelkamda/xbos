CREATE TABLE public.ledger_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    tenant_id INTEGER NOT NULL,
    legal_entity_unit_id BIGINT NOT NULL,
    parent_account_id BIGINT NULL,
    account_code VARCHAR(64) NOT NULL,
    account_name VARCHAR(180) NOT NULL,
    account_type VARCHAR(32) NOT NULL,
    normal_balance VARCHAR(8) NOT NULL,
    currency_policy VARCHAR(24) NOT NULL DEFAULT 'fixed',
    fixed_currency_code VARCHAR(12) NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    effective_from DATE NOT NULL,
    effective_to DATE NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT uq_ledger_accounts_public_id UNIQUE (public_id),
    CONSTRAINT uq_ledger_accounts_tenant_id_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_ledger_accounts_entity_code
        UNIQUE (tenant_id, legal_entity_unit_id, account_code),
    CONSTRAINT fk_ledger_accounts_tenant FOREIGN KEY (tenant_id)
        REFERENCES public.tenants(id) ON DELETE RESTRICT,
    CONSTRAINT fk_ledger_accounts_entity FOREIGN KEY
        (tenant_id, legal_entity_unit_id)
        REFERENCES public.organization_units(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_ledger_accounts_parent FOREIGN KEY
        (tenant_id, parent_account_id)
        REFERENCES public.ledger_accounts(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_ledger_accounts_currency FOREIGN KEY (fixed_currency_code)
        REFERENCES public.currency_assets(code) ON DELETE RESTRICT,
    CONSTRAINT ck_ledger_accounts_type CHECK (
        account_type IN ('asset','liability','equity','income','expense','contra','statistical')
    ),
    CONSTRAINT ck_ledger_accounts_normal_balance
        CHECK (normal_balance IN ('debit','credit')),
    CONSTRAINT ck_ledger_accounts_currency_policy
        CHECK (currency_policy IN ('any','base_only','fixed')),
    CONSTRAINT ck_ledger_accounts_fixed_currency CHECK (
        (currency_policy = 'fixed' AND fixed_currency_code IS NOT NULL) OR
        (currency_policy <> 'fixed' AND fixed_currency_code IS NULL)
    ),
    CONSTRAINT ck_ledger_accounts_effective
        CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT ck_ledger_accounts_code
        CHECK (account_code = btrim(account_code) AND length(account_code) > 0),
    CONSTRAINT ck_ledger_accounts_name
        CHECK (length(btrim(account_name)) > 0),
    CONSTRAINT ck_ledger_accounts_metadata_object
        CHECK (jsonb_typeof(metadata) = 'object')
);
