CREATE OR REPLACE FUNCTION public.xbos_validate_posted_journal_balance()
RETURNS trigger
LANGUAGE plpgsql
AS $body$
DECLARE
    selected_entry_id BIGINT;
    selected_tenant_id INTEGER;
    selected_state VARCHAR(24);
    line_count BIGINT;
    transaction_debits NUMERIC(24,8);
    transaction_credits NUMERIC(24,8);
    base_debits NUMERIC(24,8);
    base_credits NUMERIC(24,8);
BEGIN
    IF TG_TABLE_NAME = 'journal_entries' THEN
        selected_entry_id := NEW.id;
        selected_tenant_id := NEW.tenant_id;
    ELSE
        selected_entry_id := COALESCE(NEW.journal_entry_id, OLD.journal_entry_id);
        selected_tenant_id := COALESCE(NEW.tenant_id, OLD.tenant_id);
    END IF;

    SELECT entry_state
      INTO selected_state
      FROM public.journal_entries
     WHERE tenant_id = selected_tenant_id
       AND id = selected_entry_id;

    IF selected_state IN ('posted','reversed') THEN
        SELECT count(*),
               COALESCE(sum(transaction_debit_amount), 0),
               COALESCE(sum(transaction_credit_amount), 0),
               COALESCE(sum(base_debit_amount), 0),
               COALESCE(sum(base_credit_amount), 0)
          INTO line_count, transaction_debits, transaction_credits, base_debits, base_credits
          FROM public.journal_lines
         WHERE tenant_id = selected_tenant_id
           AND journal_entry_id = selected_entry_id;

        IF line_count < 2 THEN
            RAISE EXCEPTION USING MESSAGE = 'posted journal entry must contain at least two lines';
        END IF;
        IF transaction_debits <> transaction_credits THEN
            RAISE EXCEPTION USING MESSAGE = 'posted journal transaction currency is not balanced';
        END IF;
        IF base_debits <> base_credits THEN
            RAISE EXCEPTION USING MESSAGE = 'posted journal base currency is not balanced';
        END IF;
    END IF;
    RETURN NULL;
END
$body$;

CREATE CONSTRAINT TRIGGER trg_journal_entries_balanced
AFTER INSERT OR UPDATE ON public.journal_entries
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION public.xbos_validate_posted_journal_balance();

CREATE CONSTRAINT TRIGGER trg_journal_lines_balanced
AFTER INSERT OR UPDATE OR DELETE ON public.journal_lines
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION public.xbos_validate_posted_journal_balance();

CREATE OR REPLACE FUNCTION public.xbos_reject_posted_journal_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $body$
DECLARE
    protected_state VARCHAR(24);
BEGIN
    IF TG_TABLE_NAME = 'journal_entries' THEN
        protected_state := OLD.entry_state;
        IF protected_state IN ('posted','reversed') THEN
            RAISE EXCEPTION USING MESSAGE = 'posted journal entries are immutable; post a correcting entry';
        END IF;
    ELSE
        SELECT entry_state
          INTO protected_state
          FROM public.journal_entries
         WHERE tenant_id = OLD.tenant_id
           AND id = OLD.journal_entry_id;
        IF protected_state IN ('posted','reversed') THEN
            RAISE EXCEPTION USING MESSAGE = 'posted journal lines are immutable; post a correcting entry';
        END IF;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END
$body$;

CREATE TRIGGER trg_journal_entries_immutable
BEFORE UPDATE OR DELETE ON public.journal_entries
FOR EACH ROW EXECUTE FUNCTION public.xbos_reject_posted_journal_mutation();

CREATE TRIGGER trg_journal_lines_immutable
BEFORE UPDATE OR DELETE ON public.journal_lines
FOR EACH ROW EXECUTE FUNCTION public.xbos_reject_posted_journal_mutation();
