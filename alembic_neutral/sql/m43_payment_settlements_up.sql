CREATE OR REPLACE FUNCTION public.xbos_validate_payment_settlement_insert()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    intent public.canonical_payment_intents;
    attempt public.canonical_payment_attempts;
    account public.operational_financial_accounts;
BEGIN
    SELECT * INTO intent FROM public.canonical_payment_intents
    WHERE tenant_id=NEW.tenant_id AND id=NEW.payment_intent_id FOR SHARE;
    IF NOT FOUND OR intent.organization_unit_id <> NEW.organization_unit_id
       OR intent.currency_code <> NEW.currency_code THEN
        RAISE EXCEPTION USING MESSAGE='settlement intent scope or currency mismatch';
    END IF;
    IF NEW.gross_amount > intent.requested_amount THEN
        RAISE EXCEPTION USING MESSAGE='settlement exceeds payment intent amount';
    END IF;
    IF NEW.payment_attempt_id IS NOT NULL THEN
        SELECT * INTO attempt FROM public.canonical_payment_attempts
        WHERE tenant_id=NEW.tenant_id AND id=NEW.payment_attempt_id FOR SHARE;
        IF NOT FOUND OR attempt.payment_intent_id <> NEW.payment_intent_id
           OR attempt.organization_unit_id <> NEW.organization_unit_id
           OR attempt.currency_code <> NEW.currency_code
           OR attempt.attempt_state <> 'succeeded'
           OR NEW.gross_amount > attempt.attempted_amount THEN
            RAISE EXCEPTION USING MESSAGE='settlement requires matching successful attempt authority';
        END IF;
        IF attempt.payment_method_code <> NEW.payment_method_code
           OR attempt.payment_rail_code <> NEW.payment_rail_code THEN
            RAISE EXCEPTION USING MESSAGE='settlement routing differs from payment attempt';
        END IF;
    ELSIF NEW.payment_rail_code NOT IN ('cash','internal_credit') THEN
        RAISE EXCEPTION USING MESSAGE='external settlement requires payment attempt authority';
    END IF;
    SELECT * INTO account FROM public.operational_financial_accounts
    WHERE tenant_id=NEW.tenant_id AND id=NEW.operational_account_id FOR SHARE;
    IF NOT FOUND OR account.organization_unit_id <> NEW.organization_unit_id
       OR account.currency_code <> NEW.currency_code OR NOT account.active
       OR account.aggregation_role <> 'leaf' THEN
        RAISE EXCEPTION USING MESSAGE='settlement operational account is unavailable';
    END IF;
    IF NEW.settlement_state <> 'pending' OR NEW.row_version <> 1
       OR NEW.terminal_at IS NOT NULL OR NEW.failure_code IS NOT NULL
       OR NEW.reversed_amount <> 0 THEN
        RAISE EXCEPTION USING MESSAGE='settlement must begin pending with version one';
    END IF;
    RETURN NEW;
END;
$$;

