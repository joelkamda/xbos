    payment_settlement_id BIGINT NOT NULL,
    sequence_number INTEGER NOT NULL,
    from_state VARCHAR(32) NULL,
    to_state VARCHAR(32) NOT NULL,
    reason_code VARCHAR(80) NOT NULL,
    finality_status VARCHAR(24) NOT NULL,
    availability_state VARCHAR(24) NOT NULL,
    failure_code VARCHAR(80) NULL,
    external_settlement_reference_snapshot VARCHAR(255) NULL,
    value_date_snapshot DATE NOT NULL,
    evidence_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    business_date DATE NOT NULL,
    calendar_policy_version INTEGER NOT NULL,
    correlation_id UUID NOT NULL,
    actor_user_id INTEGER NULL,
    actor_service VARCHAR(120) NULL,
    source_component VARCHAR(120) NOT NULL,
    source_record_id VARCHAR(200) NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_payment_settlement_transitions_public_id UNIQUE (public_id),
    CONSTRAINT uq_payment_settlement_transitions_sequence
        UNIQUE (tenant_id, payment_settlement_id, sequence_number),
    CONSTRAINT uq_payment_settlement_transitions_source
        UNIQUE (tenant_id, source_component, source_record_id),
    CONSTRAINT fk_payment_settlement_transitions_settlement FOREIGN KEY
        (tenant_id, organization_unit_id, payment_settlement_id)
        REFERENCES public.payment_settlements
        (tenant_id, organization_unit_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_payment_settlement_transitions_actor FOREIGN KEY
        (tenant_id, actor_user_id)
        REFERENCES public.users(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_payment_settlement_transitions_sequence CHECK (sequence_number > 0),
    CONSTRAINT ck_payment_settlement_transitions_from CHECK (
        from_state IS NULL OR from_state IN
        ('pending','confirmed','failed','partially_reversed','reversed')
    ),
    CONSTRAINT ck_payment_settlement_transitions_to CHECK (
        to_state IN ('pending','confirmed','failed','partially_reversed','reversed')
    ),
    CONSTRAINT ck_payment_settlement_transitions_reason
        CHECK (reason_code ~ '^[a-z][a-z0-9_.-]{0,79}$'),
    CONSTRAINT ck_payment_settlement_transitions_failure CHECK (
        (to_state = 'failed' AND failure_code IS NOT NULL)
        OR (to_state <> 'failed' AND failure_code IS NULL)
    ),
    CONSTRAINT ck_payment_settlement_transitions_finality CHECK (
        finality_status IN ('unverified','provisional','final','rejected','not_applicable')
    ),
    CONSTRAINT ck_payment_settlement_transitions_availability CHECK (
        availability_state IN ('pending','available','reserved','released','unavailable')
    ),
    CONSTRAINT ck_payment_settlement_transitions_evidence
        CHECK (jsonb_typeof(evidence_payload) = 'object'),
    CONSTRAINT ck_payment_settlement_transitions_calendar
        CHECK (calendar_policy_version > 0),
    CONSTRAINT ck_payment_settlement_transitions_actor CHECK (
        actor_user_id IS NOT NULL
        OR (actor_service IS NOT NULL AND length(btrim(actor_service)) > 0)
    ),
    CONSTRAINT ck_payment_settlement_transitions_metadata
        CHECK (jsonb_typeof(metadata) = 'object')
);

