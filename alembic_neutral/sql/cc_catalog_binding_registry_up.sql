CREATE TABLE public.restaurant_customer_catalog_read_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    tenant_id INTEGER NOT NULL,
    merchant_public_id UUID NOT NULL,
    location_id BIGINT NOT NULL,
    catalog_public_id UUID NOT NULL,
    price_code VARCHAR(80) NOT NULL,
    currency CHAR(3) NOT NULL,
    scope_type VARCHAR(24) NOT NULL,
    scope_id BIGINT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ NULL,
    row_version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_cc_catalog_binding_public UNIQUE(public_id),
    CONSTRAINT uq_cc_catalog_binding_tenant_public UNIQUE(tenant_id,public_id),
    CONSTRAINT fk_cc_catalog_binding_tenant
        FOREIGN KEY(tenant_id) REFERENCES public.tenants(id) ON DELETE RESTRICT,
    CONSTRAINT fk_cc_catalog_binding_location
        FOREIGN KEY(tenant_id,location_id)
        REFERENCES public.locations(tenant_id,id) ON DELETE RESTRICT,
    CONSTRAINT fk_cc_catalog_binding_merchant
        FOREIGN KEY(merchant_public_id)
        REFERENCES public.pa_merchants(public_id) ON DELETE RESTRICT,
    CONSTRAINT fk_cc_catalog_binding_catalog
        FOREIGN KEY(catalog_public_id)
        REFERENCES public.so1_catalogs(public_id) ON DELETE RESTRICT,
    CONSTRAINT ck_cc_catalog_binding_window
        CHECK(effective_to IS NULL OR effective_to>effective_from),
    CONSTRAINT ck_cc_catalog_binding_version CHECK(row_version>=1),
    CONSTRAINT ck_cc_catalog_binding_price_code
        CHECK(
            price_code=lower(btrim(price_code))
            AND length(price_code)>0
        ),
    CONSTRAINT ck_cc_catalog_binding_currency
        CHECK(currency~'^[A-Z]{3}$'),
    CONSTRAINT ck_cc_catalog_binding_scope
        CHECK(
            scope_type IN (
                'tenant',
                'legal_entity',
                'organization_unit',
                'location'
            )
            AND (
                (scope_type='tenant' AND scope_id IS NULL)
                OR (
                    scope_type<>'tenant'
                    AND scope_id IS NOT NULL
                )
            )
            AND (
                scope_type<>'location'
                OR scope_id=location_id
            )
        )
);

CREATE INDEX ix_cc_catalog_binding_resolution
    ON public.restaurant_customer_catalog_read_bindings(
        merchant_public_id,
        location_id,
        active,
        effective_from,
        effective_to,
        row_version
    );

CREATE OR REPLACE FUNCTION public.cc_validate_catalog_read_binding()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    pair_key BIGINT;
BEGIN
    pair_key := hashtextextended(
        NEW.tenant_id::text || ':' ||
        NEW.merchant_public_id::text || ':' ||
        NEW.location_id::text,
        0
    );
    PERFORM pg_advisory_xact_lock(pair_key);

    IF NOT EXISTS(
        SELECT 1
        FROM public.pa_merchants m
        WHERE m.public_id=NEW.merchant_public_id
          AND m.tenant_id=NEW.tenant_id
    ) THEN
        RAISE EXCEPTION 'cross_tenant_catalog_binding_merchant'
            USING ERRCODE='23514';
    END IF;

    IF NOT EXISTS(
        SELECT 1
        FROM public.so1_catalogs c
        WHERE c.public_id=NEW.catalog_public_id
          AND c.tenant_id=NEW.tenant_id
    ) THEN
        RAISE EXCEPTION 'cross_tenant_catalog_binding_catalog'
            USING ERRCODE='23514';
    END IF;
    IF NEW.active AND EXISTS(
        SELECT 1
        FROM public.restaurant_customer_catalog_read_bindings b
        WHERE b.tenant_id=NEW.tenant_id
          AND b.merchant_public_id=NEW.merchant_public_id
          AND b.location_id=NEW.location_id
          AND b.active=true
          AND b.id<>COALESCE(NEW.id,0)
          AND tstzrange(
              b.effective_from,
              COALESCE(b.effective_to,'infinity'),
              '[)'
          ) && tstzrange(
              NEW.effective_from,
              COALESCE(NEW.effective_to,'infinity'),
              '[)'
          )
    ) THEN
        RAISE EXCEPTION 'overlapping_active_catalog_read_binding'
            USING ERRCODE='23514';
    END IF;

    IF TG_OP='UPDATE' THEN
        NEW.row_version := OLD.row_version + 1;
        NEW.updated_at := now();
    END IF;

    RETURN NEW;
END
$$;
CREATE TRIGGER trg_cc_catalog_read_binding_validate
BEFORE INSERT OR UPDATE
ON public.restaurant_customer_catalog_read_bindings
FOR EACH ROW
EXECUTE FUNCTION public.cc_validate_catalog_read_binding();

COMMENT ON TABLE public.restaurant_customer_catalog_read_bindings IS
'XBOS-owned Customer Channel registry binding canonical merchant/location context to an effective SO1 catalog and pricing selection context; contains no catalog items, product names, price amounts, or menu sections.';
