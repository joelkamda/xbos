CREATE TABLE public.operational_account_authorities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    tenant_id INTEGER NOT NULL,
    organization_unit_id BIGINT NOT NULL,
    operational_account_id BIGINT NOT NULL,
    source_component VARCHAR(120) NOT NULL,
    source_record_id VARCHAR(191) NOT NULL,
    idempotency_scope VARCHAR(80) NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    correlation_id UUID NOT NULL,
    actor_user_id INTEGER NULL,
    actor_service VARCHAR(120) NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT uq_operational_account_authorities_public UNIQUE (public_id),
    CONSTRAINT uq_operational_account_authorities_account UNIQUE (tenant_id, operational_account_id),
    CONSTRAINT uq_operational_account_authorities_idempotency UNIQUE (tenant_id, idempotency_scope, idempotency_key),
    CONSTRAINT fk_operational_account_authorities_account FOREIGN KEY (tenant_id, operational_account_id)
        REFERENCES public.operational_financial_accounts(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_operational_account_authorities_org FOREIGN KEY (tenant_id, organization_unit_id)
        REFERENCES public.organization_units(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_operational_account_authorities_actor FOREIGN KEY (tenant_id, actor_user_id)
        REFERENCES public.users(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_operational_account_authorities_actor CHECK (
        actor_user_id IS NOT NULL OR NULLIF(btrim(actor_service), '') IS NOT NULL
    ),
    CONSTRAINT ck_operational_account_authorities_identity CHECK (
        length(btrim(source_component)) > 0 AND length(btrim(source_record_id)) > 0
        AND length(btrim(idempotency_scope)) > 0 AND length(btrim(idempotency_key)) > 0
    ),
    CONSTRAINT ck_operational_account_authorities_fingerprint CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_operational_account_authorities_metadata CHECK (jsonb_typeof(metadata) = 'object')
);

