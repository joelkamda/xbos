CREATE OR REPLACE FUNCTION public.xbos_validate_operational_account_hierarchy()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE parent_row public.operational_financial_accounts%ROWTYPE;
BEGIN
    IF NEW.parent_account_id IS NOT NULL THEN
        SELECT * INTO parent_row FROM public.operational_financial_accounts
        WHERE tenant_id=NEW.tenant_id AND id=NEW.parent_account_id;
        IF NOT FOUND OR parent_row.organization_unit_id<>NEW.organization_unit_id
           OR parent_row.currency_code<>NEW.currency_code
           OR parent_row.aggregation_role<>'parent_aggregate' THEN
            RAISE EXCEPTION 'operational account parent scope, currency, or aggregation role differs'
                USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION public.xbos_protect_operational_account_identity()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'operational financial account is durable; deactivate it instead' USING ERRCODE='55000';
    END IF;
    IF ROW(NEW.public_id,NEW.tenant_id,NEW.organization_unit_id,NEW.parent_account_id,
           NEW.account_class,NEW.account_type,NEW.code,NEW.currency_code,NEW.aggregation_role,NEW.opened_at)
       IS DISTINCT FROM
       ROW(OLD.public_id,OLD.tenant_id,OLD.organization_unit_id,OLD.parent_account_id,
           OLD.account_class,OLD.account_type,OLD.code,OLD.currency_code,OLD.aggregation_role,OLD.opened_at) THEN
        RAISE EXCEPTION 'operational account identity, scope, hierarchy, currency, and opening are immutable'
            USING ERRCODE='55000';
    END IF;
    RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION public.xbos_validate_operational_balance_fact()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE account_row public.operational_financial_accounts%ROWTYPE;
DECLARE fact_at TIMESTAMPTZ;
BEGIN
    SELECT * INTO account_row FROM public.operational_financial_accounts
    WHERE tenant_id=NEW.tenant_id AND id=NEW.operational_account_id FOR SHARE;
    IF TG_TABLE_NAME='operational_account_balance_anchors' THEN
        fact_at := NEW.anchor_at;
    ELSIF TG_TABLE_NAME='operational_account_balance_observations' THEN
        fact_at := NEW.observed_at;
    ELSE
        RAISE EXCEPTION 'unexpected operational balance fact trigger table: %', TG_TABLE_NAME
            USING ERRCODE='55000';
    END IF;
    IF NOT FOUND OR account_row.organization_unit_id<>NEW.organization_unit_id
       OR account_row.currency_code<>NEW.currency_code OR account_row.aggregation_role<>'leaf' THEN
        RAISE EXCEPTION 'balance fact account scope, currency, or aggregation role differs' USING ERRCODE='23514';
    END IF;
    IF fact_at<account_row.opened_at OR (account_row.closed_at IS NOT NULL AND fact_at>account_row.closed_at) THEN
        RAISE EXCEPTION 'balance fact falls outside operational account lifetime' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_operational_account_hierarchy
BEFORE INSERT OR UPDATE ON public.operational_financial_accounts
FOR EACH ROW EXECUTE FUNCTION public.xbos_validate_operational_account_hierarchy();
