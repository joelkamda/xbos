CREATE OR REPLACE FUNCTION public.sc41_validate_semantic_taxonomy_placement()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    child_system BIGINT;
    child_tenant INTEGER;
    parent_system BIGINT;
    parent_tenant INTEGER;
    candidate_range TSTZRANGE;
BEGIN
    SELECT taxonomy_system_id,tenant_id INTO child_system,child_tenant
      FROM public.semantic_taxonomy_nodes WHERE id=NEW.semantic_taxonomy_node_id;

    IF child_tenant IS NULL AND NEW.source_type='tenant' THEN
        RAISE EXCEPTION 'tenant_source_requires_tenant_taxonomy_node' USING ERRCODE='23514';
    END IF;
    IF child_tenant IS NOT NULL AND NEW.source_type NOT IN ('tenant','migration') THEN
        RAISE EXCEPTION 'tenant_taxonomy_node_requires_tenant_or_migration_source' USING ERRCODE='23514';
    END IF;

    IF EXISTS (
        SELECT 1 FROM public.semantic_taxonomy_placements p
        WHERE p.semantic_taxonomy_node_id=NEW.semantic_taxonomy_node_id
          AND p.id<>COALESCE(NEW.id,0)
          AND tstzrange(p.effective_from,COALESCE(p.effective_to,'infinity'::timestamptz),'[)')
              && tstzrange(NEW.effective_from,COALESCE(NEW.effective_to,'infinity'::timestamptz),'[)')
    ) THEN
        RAISE EXCEPTION 'overlapping_taxonomy_placement' USING ERRCODE='23514';
    END IF;

    IF NEW.parent_node_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT taxonomy_system_id,tenant_id INTO parent_system,parent_tenant
      FROM public.semantic_taxonomy_nodes WHERE id=NEW.parent_node_id;
    IF parent_system IS DISTINCT FROM child_system THEN
        RAISE EXCEPTION 'cross_taxonomy_system_parent_forbidden' USING ERRCODE='23514';
    END IF;
    IF child_tenant IS NULL AND parent_tenant IS NOT NULL THEN
        RAISE EXCEPTION 'global_taxonomy_node_cannot_inherit_tenant_parent' USING ERRCODE='23514';
    END IF;
    IF child_tenant IS NOT NULL AND parent_tenant IS NOT NULL AND parent_tenant<>child_tenant THEN
        RAISE EXCEPTION 'cross_tenant_taxonomy_parent_forbidden' USING ERRCODE='23514';
    END IF;

    candidate_range := tstzrange(NEW.effective_from,COALESCE(NEW.effective_to,'infinity'::timestamptz),'[)');
    IF EXISTS (
        WITH RECURSIVE ancestors(node_id,valid_range) AS (
            SELECT NEW.parent_node_id,candidate_range
            UNION ALL
            SELECT p.parent_node_id,
                   a.valid_range * tstzrange(p.effective_from,COALESCE(p.effective_to,'infinity'::timestamptz),'[)')
            FROM ancestors a
            JOIN public.semantic_taxonomy_placements p ON p.semantic_taxonomy_node_id=a.node_id
            WHERE p.parent_node_id IS NOT NULL
              AND a.valid_range && tstzrange(p.effective_from,COALESCE(p.effective_to,'infinity'::timestamptz),'[)')
        )
        SELECT 1 FROM ancestors WHERE node_id=NEW.semantic_taxonomy_node_id
    ) THEN
        RAISE EXCEPTION 'taxonomy_cycle' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_sc41_semantic_taxonomy_placement_validate
BEFORE INSERT ON public.semantic_taxonomy_placements
FOR EACH ROW EXECUTE FUNCTION public.sc41_validate_semantic_taxonomy_placement();

CREATE OR REPLACE FUNCTION public.sc41_assert_effective_taxonomy_acyclic(
    p_taxonomy_system_id BIGINT,
    p_tenant_id INTEGER,
    p_effective_from TIMESTAMPTZ,
    p_effective_to TIMESTAMPTZ
)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    check_at TIMESTAMPTZ;
    cycle_found BOOLEAN;
BEGIN
    FOR check_at IN
        SELECT DISTINCT boundary
        FROM (
            SELECT p_effective_from AS boundary
            UNION ALL
            SELECT p.effective_from
              FROM public.semantic_taxonomy_placements p
              JOIN public.semantic_taxonomy_nodes n ON n.id=p.semantic_taxonomy_node_id
             WHERE n.taxonomy_system_id=p_taxonomy_system_id
               AND p.effective_from>=p_effective_from
               AND (p_effective_to IS NULL OR p.effective_from<p_effective_to)
            UNION ALL
            SELECT p.effective_to
              FROM public.semantic_taxonomy_placements p
              JOIN public.semantic_taxonomy_nodes n ON n.id=p.semantic_taxonomy_node_id
             WHERE n.taxonomy_system_id=p_taxonomy_system_id
               AND p.effective_to IS NOT NULL
               AND p.effective_to>=p_effective_from
               AND (p_effective_to IS NULL OR p.effective_to<p_effective_to)
            UNION ALL
            SELECT o.effective_from
              FROM public.tenant_taxonomy_overlays o
              JOIN public.semantic_taxonomy_nodes n ON n.id=o.semantic_taxonomy_node_id
             WHERE p_tenant_id IS NOT NULL
               AND o.tenant_id=p_tenant_id
               AND n.taxonomy_system_id=p_taxonomy_system_id
               AND o.effective_from>=p_effective_from
               AND (p_effective_to IS NULL OR o.effective_from<p_effective_to)
            UNION ALL
            SELECT o.effective_to
              FROM public.tenant_taxonomy_overlays o
              JOIN public.semantic_taxonomy_nodes n ON n.id=o.semantic_taxonomy_node_id
             WHERE p_tenant_id IS NOT NULL
               AND o.tenant_id=p_tenant_id
               AND n.taxonomy_system_id=p_taxonomy_system_id
               AND o.effective_to IS NOT NULL
               AND o.effective_to>=p_effective_from
               AND (p_effective_to IS NULL OR o.effective_to<p_effective_to)
        ) boundaries
        WHERE boundary IS NOT NULL
        ORDER BY boundary
    LOOP
        WITH RECURSIVE visible_nodes AS (
            SELECT n.id
              FROM public.semantic_taxonomy_nodes n
             WHERE n.taxonomy_system_id=p_taxonomy_system_id
               AND (
                    (p_tenant_id IS NULL AND n.tenant_id IS NULL)
                    OR
                    (p_tenant_id IS NOT NULL AND (n.tenant_id IS NULL OR n.tenant_id=p_tenant_id))
               )
        ), active_placements AS (
            SELECT DISTINCT ON (p.semantic_taxonomy_node_id)
                   p.semantic_taxonomy_node_id AS child_id,
                   p.parent_node_id AS base_parent_id
              FROM public.semantic_taxonomy_placements p
              JOIN visible_nodes v ON v.id=p.semantic_taxonomy_node_id
             WHERE p.effective_from<=check_at
               AND (p.effective_to IS NULL OR check_at<p.effective_to)
             ORDER BY p.semantic_taxonomy_node_id,p.effective_from DESC,p.placement_version DESC
        ), active_overlays AS (
            SELECT DISTINCT ON (o.semantic_taxonomy_node_id)
                   o.semantic_taxonomy_node_id AS child_id,
                   o.parent_override_node_id,
                   o.has_parent_override
              FROM public.tenant_taxonomy_overlays o
              JOIN visible_nodes v ON v.id=o.semantic_taxonomy_node_id
             WHERE p_tenant_id IS NOT NULL
               AND o.tenant_id=p_tenant_id
               AND o.effective_from<=check_at
               AND (o.effective_to IS NULL OR check_at<o.effective_to)
             ORDER BY o.semantic_taxonomy_node_id,o.effective_from DESC,o.overlay_version DESC
        ), edges AS (
            SELECT p.child_id,
                   CASE WHEN o.has_parent_override
                        THEN o.parent_override_node_id ELSE p.base_parent_id END AS parent_id
              FROM active_placements p
              LEFT JOIN active_overlays o ON o.child_id=p.child_id
        ), walk(start_id,current_id,visited,cycle) AS (
            SELECT e.child_id,e.parent_id,ARRAY[e.child_id]::BIGINT[],
                   (e.parent_id=e.child_id)
              FROM edges e
             WHERE e.parent_id IS NOT NULL
            UNION ALL
            SELECT w.start_id,e.parent_id,w.visited||w.current_id,
                   (e.parent_id=ANY(w.visited||w.current_id))
              FROM walk w
              JOIN edges e ON e.child_id=w.current_id
             WHERE w.current_id IS NOT NULL AND NOT w.cycle
        )
        SELECT EXISTS(SELECT 1 FROM walk WHERE cycle) INTO cycle_found;

        IF cycle_found THEN
            RAISE EXCEPTION 'effective_taxonomy_cycle' USING ERRCODE='23514';
        END IF;
    END LOOP;
END $$;

CREATE OR REPLACE FUNCTION public.sc41_validate_effective_cycles_after_placement()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    system_id BIGINT;
    node_tenant INTEGER;
    overlay_tenant INTEGER;
BEGIN
    SELECT taxonomy_system_id,tenant_id INTO system_id,node_tenant
      FROM public.semantic_taxonomy_nodes WHERE id=NEW.semantic_taxonomy_node_id;

    IF node_tenant IS NULL THEN
        PERFORM public.sc41_assert_effective_taxonomy_acyclic(system_id,NULL,NEW.effective_from,NEW.effective_to);
        FOR overlay_tenant IN
            SELECT DISTINCT o.tenant_id
              FROM public.tenant_taxonomy_overlays o
              JOIN public.semantic_taxonomy_nodes n ON n.id=o.semantic_taxonomy_node_id
             WHERE n.taxonomy_system_id=system_id
               AND tstzrange(o.effective_from,COALESCE(o.effective_to,'infinity'::timestamptz),'[)')
                   && tstzrange(NEW.effective_from,COALESCE(NEW.effective_to,'infinity'::timestamptz),'[)')
        LOOP
            PERFORM public.sc41_assert_effective_taxonomy_acyclic(system_id,overlay_tenant,NEW.effective_from,NEW.effective_to);
        END LOOP;
    ELSE
        PERFORM public.sc41_assert_effective_taxonomy_acyclic(system_id,node_tenant,NEW.effective_from,NEW.effective_to);
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_sc41_semantic_taxonomy_placement_effective_cycle
AFTER INSERT ON public.semantic_taxonomy_placements
FOR EACH ROW EXECUTE FUNCTION public.sc41_validate_effective_cycles_after_placement();

CREATE OR REPLACE FUNCTION public.sc41_protect_semantic_taxonomy_placement()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'semantic_taxonomy_placement_is_historical' USING ERRCODE='23514';
    END IF;
    IF OLD.effective_to IS NOT NULL OR NEW.effective_to IS NULL OR NEW.effective_to<=OLD.effective_from THEN
        RAISE EXCEPTION 'invalid_taxonomy_placement_close' USING ERRCODE='23514';
    END IF;
    IF NEW.semantic_taxonomy_node_id<>OLD.semantic_taxonomy_node_id
       OR NEW.placement_version<>OLD.placement_version
       OR NEW.parent_node_id IS DISTINCT FROM OLD.parent_node_id
       OR NEW.sort_order<>OLD.sort_order
       OR NEW.effective_from<>OLD.effective_from
       OR NEW.source_type<>OLD.source_type
       OR NEW.source_key<>OLD.source_key
       OR NEW.provenance<>OLD.provenance
       OR NEW.public_id<>OLD.public_id THEN
        RAISE EXCEPTION 'semantic_taxonomy_placement_mutation_forbidden' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_sc41_semantic_taxonomy_placement_protect
BEFORE UPDATE OR DELETE ON public.semantic_taxonomy_placements
FOR EACH ROW EXECUTE FUNCTION public.sc41_protect_semantic_taxonomy_placement();

