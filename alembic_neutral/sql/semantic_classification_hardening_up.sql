CREATE OR REPLACE FUNCTION public.sc41_validate_semantic_taxonomy_node_scope()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    system_tenant INTEGER;
    namespace_scope VARCHAR(16);
    namespace_tenant INTEGER;
BEGIN
    SELECT s.tenant_id INTO system_tenant
      FROM public.taxonomy_systems s WHERE s.id=NEW.taxonomy_system_id;
    SELECT ns.scope,ns.tenant_id INTO namespace_scope,namespace_tenant
      FROM public.semantic_concepts c
      JOIN public.semantic_namespaces ns ON ns.id=c.namespace_id
      WHERE c.id=NEW.semantic_concept_id;

    IF system_tenant IS NOT NULL AND NEW.tenant_id IS DISTINCT FROM system_tenant THEN
        RAISE EXCEPTION 'semantic_taxonomy_system_scope_mismatch' USING ERRCODE='23514';
    END IF;
    IF namespace_scope='tenant' THEN
        IF NEW.tenant_id IS DISTINCT FROM namespace_tenant THEN
            RAISE EXCEPTION 'tenant_semantic_concept_scope_mismatch' USING ERRCODE='23514';
        END IF;
    ELSIF NEW.tenant_id IS NOT NULL THEN
        RAISE EXCEPTION 'non_tenant_concept_requires_global_taxonomy_node' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
