CREATE OR REPLACE FUNCTION public.sc41_validate_semantic_classification_governance()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    assignment_concept BIGINT;
    assignment_tenant INTEGER;
    node_concept BIGINT;
    node_tenant INTEGER;
BEGIN
    SELECT concept_id,tenant_id INTO assignment_concept,assignment_tenant
      FROM public.classification_assignments WHERE id=NEW.assignment_id;
    IF NEW.semantic_taxonomy_node_id IS NOT NULL THEN
        SELECT semantic_concept_id,tenant_id INTO node_concept,node_tenant
          FROM public.semantic_taxonomy_nodes WHERE id=NEW.semantic_taxonomy_node_id;
        IF node_concept IS DISTINCT FROM assignment_concept THEN
            RAISE EXCEPTION 'classification_node_concept_mismatch' USING ERRCODE='23514';
        END IF;
        IF node_tenant IS NOT NULL AND node_tenant<>assignment_tenant THEN
            RAISE EXCEPTION 'cross_tenant_semantic_classification_forbidden' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_sc41_semantic_classification_governance_validate
BEFORE INSERT ON public.semantic_classification_governance
FOR EACH ROW EXECUTE FUNCTION public.sc41_validate_semantic_classification_governance();

CREATE OR REPLACE FUNCTION public.sc41_protect_semantic_classification_governance()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'semantic_classification_governance_is_historical' USING ERRCODE='23514';
    END IF;
    IF OLD.effective_to IS NOT NULL OR NEW.effective_to IS NULL OR NEW.effective_to<=OLD.effective_from THEN
        RAISE EXCEPTION 'invalid_semantic_classification_close' USING ERRCODE='23514';
    END IF;
    IF NEW.assignment_id<>OLD.assignment_id
       OR NEW.semantic_taxonomy_node_id IS DISTINCT FROM OLD.semantic_taxonomy_node_id
       OR NEW.assignment_mode<>OLD.assignment_mode
       OR NEW.source_type<>OLD.source_type
       OR NEW.source_key<>OLD.source_key
       OR NEW.effective_from<>OLD.effective_from
       OR NEW.provenance<>OLD.provenance THEN
        RAISE EXCEPTION 'semantic_classification_governance_mutation_forbidden' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_sc41_semantic_classification_governance_protect
BEFORE UPDATE OR DELETE ON public.semantic_classification_governance
FOR EACH ROW EXECUTE FUNCTION public.sc41_protect_semantic_classification_governance();

