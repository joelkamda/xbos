BEFORE INSERT OR UPDATE OF taxonomy_system_id,semantic_concept_id,tenant_id
ON public.semantic_taxonomy_nodes FOR EACH ROW
EXECUTE FUNCTION public.sc41_validate_semantic_taxonomy_node_scope();

