CREATE OR REPLACE FUNCTION public.sc41_validate_tenant_taxonomy_overlay()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    node_system BIGINT;
    node_tenant INTEGER;
    parent_system BIGINT;
    parent_tenant INTEGER;
BEGIN
    SELECT taxonomy_system_id,tenant_id INTO node_system,node_tenant
      FROM public.semantic_taxonomy_nodes WHERE id=NEW.semantic_taxonomy_node_id;
    IF node_tenant IS NOT NULL AND node_tenant<>NEW.tenant_id THEN
        RAISE EXCEPTION 'cross_tenant_taxonomy_overlay_forbidden' USING ERRCODE='23514';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.tenant_taxonomy_overlays o
        WHERE o.tenant_id=NEW.tenant_id
          AND o.semantic_taxonomy_node_id=NEW.semantic_taxonomy_node_id
          AND o.id<>COALESCE(NEW.id,0)
          AND tstzrange(o.effective_from,COALESCE(o.effective_to,'infinity'::timestamptz),'[)')
              && tstzrange(NEW.effective_from,COALESCE(NEW.effective_to,'infinity'::timestamptz),'[)')
    ) THEN
        RAISE EXCEPTION 'overlapping_tenant_taxonomy_overlay' USING ERRCODE='23514';
    END IF;
    IF NEW.parent_override_node_id IS NOT NULL THEN
        SELECT taxonomy_system_id,tenant_id INTO parent_system,parent_tenant
          FROM public.semantic_taxonomy_nodes WHERE id=NEW.parent_override_node_id;
        IF parent_system IS DISTINCT FROM node_system THEN
            RAISE EXCEPTION 'cross_taxonomy_system_parent_override_forbidden' USING ERRCODE='23514';
        END IF;
        IF parent_tenant IS NOT NULL AND parent_tenant<>NEW.tenant_id THEN
            RAISE EXCEPTION 'cross_tenant_parent_override_forbidden' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
