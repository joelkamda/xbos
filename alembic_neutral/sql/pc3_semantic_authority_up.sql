CREATE OR REPLACE FUNCTION public.pc3_reject_taxonomy_cycle() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN IF NEW.parent_id IS NULL THEN RETURN NEW; END IF;
 IF EXISTS(WITH RECURSIVE ancestors(id,parent_id) AS (
  SELECT id,parent_id FROM public.taxonomy_nodes WHERE tenant_id=NEW.tenant_id AND id=NEW.parent_id
  UNION ALL SELECT p.id,p.parent_id FROM public.taxonomy_nodes p JOIN ancestors c ON p.id=c.parent_id WHERE p.tenant_id=NEW.tenant_id
 ) SELECT 1 FROM ancestors WHERE id=NEW.id)
 THEN RAISE EXCEPTION 'taxonomy_cycle' USING ERRCODE='23514'; END IF; RETURN NEW; END $$;
CREATE TRIGGER trg_pc3_taxonomy_cycle BEFORE INSERT OR UPDATE OF tenant_id,parent_id ON public.taxonomy_nodes FOR EACH ROW EXECUTE FUNCTION public.pc3_reject_taxonomy_cycle();
