CREATE TABLE public.semantic_namespaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    namespace_code VARCHAR(120) NOT NULL,
    scope VARCHAR(16) NOT NULL,
    owner_code VARCHAR(120) NOT NULL,
    tenant_id INTEGER NULL,
    lifecycle VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_semantic_namespaces_public_id UNIQUE(public_id),
    CONSTRAINT uq_semantic_namespaces_code UNIQUE(namespace_code),
    CONSTRAINT fk_semantic_namespaces_tenant FOREIGN KEY(tenant_id) REFERENCES public.tenants(id) ON DELETE RESTRICT,
    CONSTRAINT ck_semantic_namespaces_scope CHECK(scope IN ('kernel','finance','pack','tenant','external')),
    CONSTRAINT ck_semantic_namespaces_owner CHECK(length(btrim(owner_code))>0),
    CONSTRAINT ck_semantic_namespaces_lifecycle CHECK(lifecycle IN ('active','deprecated','retired')),
    CONSTRAINT ck_semantic_namespaces_tenant_scope CHECK((scope='tenant' AND tenant_id IS NOT NULL) OR (scope<>'tenant' AND tenant_id IS NULL))
);
