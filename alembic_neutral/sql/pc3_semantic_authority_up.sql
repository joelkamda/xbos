CREATE TABLE public.semantic_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(), concept_id BIGINT NOT NULL,
    version_number INTEGER NOT NULL, effective_from DATE NOT NULL, effective_to DATE NULL,
    canonical_label VARCHAR(240) NOT NULL, definition TEXT NOT NULL,
    definition_fingerprint CHAR(64) NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_semantic_versions_public_id UNIQUE(public_id),
    CONSTRAINT uq_semantic_versions_number UNIQUE(concept_id,version_number),
    CONSTRAINT uq_semantic_versions_start UNIQUE(concept_id,effective_from),
    CONSTRAINT fk_semantic_versions_concept FOREIGN KEY(concept_id) REFERENCES public.semantic_concepts(id) ON DELETE RESTRICT,
    CONSTRAINT ck_semantic_versions_number CHECK(version_number>=1),
    CONSTRAINT ck_semantic_versions_period CHECK(effective_to IS NULL OR effective_to>=effective_from),
    CONSTRAINT ck_semantic_versions_label CHECK(length(btrim(canonical_label))>0),
    CONSTRAINT ck_semantic_versions_definition CHECK(length(btrim(definition))>0),
    CONSTRAINT ck_semantic_versions_fingerprint CHECK(definition_fingerprint~'^[0-9a-f]{64}$')
);
CREATE INDEX ix_semantic_versions_effective ON public.semantic_versions(concept_id,effective_from,effective_to);
CREATE OR REPLACE FUNCTION public.pc3_reject_overlapping_semantic_versions() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM public.semantic_versions v WHERE v.concept_id=NEW.concept_id AND v.id<>COALESCE(NEW.id,0)
  AND daterange(v.effective_from,COALESCE(v.effective_to,'infinity'::date),'[]') && daterange(NEW.effective_from,COALESCE(NEW.effective_to,'infinity'::date),'[]'))
 THEN RAISE EXCEPTION 'overlapping_semantic_version' USING ERRCODE='23514'; END IF; RETURN NEW;
END $$;
CREATE TRIGGER trg_pc3_semantic_version_overlap BEFORE INSERT OR UPDATE ON public.semantic_versions FOR EACH ROW EXECUTE FUNCTION public.pc3_reject_overlapping_semantic_versions();
