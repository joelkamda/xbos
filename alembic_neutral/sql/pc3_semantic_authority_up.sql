    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(), namespace_id BIGINT NOT NULL,
    code VARCHAR(120) NOT NULL, lifecycle VARCHAR(16) NOT NULL DEFAULT 'active',
    superseded_by_concept_id BIGINT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_semantic_concepts_public_id UNIQUE(public_id),
    CONSTRAINT uq_semantic_concepts_namespace_code UNIQUE(namespace_id,code),
    CONSTRAINT fk_semantic_concepts_namespace FOREIGN KEY(namespace_id) REFERENCES public.semantic_namespaces(id) ON DELETE RESTRICT,
    CONSTRAINT fk_semantic_concepts_superseded FOREIGN KEY(superseded_by_concept_id) REFERENCES public.semantic_concepts(id) ON DELETE RESTRICT,
    CONSTRAINT ck_semantic_concepts_code CHECK(code=lower(btrim(code)) AND length(code)>0),
    CONSTRAINT ck_semantic_concepts_lifecycle CHECK(lifecycle IN ('active','deprecated','retired')),
    CONSTRAINT ck_semantic_concepts_superseded CHECK(superseded_by_concept_id IS NULL OR superseded_by_concept_id<>id)
