CREATE TABLE public.parties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    tenant_id INTEGER NOT NULL,
    party_kind VARCHAR(16) NOT NULL,
    display_name VARCHAR(240) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    row_version INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT uq_parties_public_id UNIQUE(public_id),
    CONSTRAINT uq_parties_tenant_id_id UNIQUE(tenant_id,id),
    CONSTRAINT fk_parties_tenant FOREIGN KEY(tenant_id) REFERENCES public.tenants(id) ON DELETE RESTRICT,
    CONSTRAINT ck_parties_kind CHECK(party_kind IN ('person','organization')),
    CONSTRAINT ck_parties_status CHECK(status IN ('active','inactive','retired')),
    CONSTRAINT ck_parties_display_name CHECK(length(btrim(display_name))>0),
    CONSTRAINT ck_parties_version CHECK(row_version>=1)
);
CREATE INDEX ix_parties_tenant_name ON public.parties(tenant_id,lower(display_name),public_id);

CREATE TABLE public.persons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id INTEGER NOT NULL,
    party_id BIGINT NOT NULL,
    given_name VARCHAR(120) NOT NULL,
    family_name VARCHAR(120) NOT NULL,
