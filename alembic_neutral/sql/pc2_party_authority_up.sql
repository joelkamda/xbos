    CONSTRAINT ck_persons_names CHECK(length(btrim(given_name))>0 AND length(btrim(family_name))>0)
);

CREATE TABLE public.organization_parties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id INTEGER NOT NULL,
    party_id BIGINT NOT NULL,
    legal_name VARCHAR(240) NOT NULL,
    registration_reference VARCHAR(160) NULL,
    CONSTRAINT uq_organization_parties_party UNIQUE(tenant_id,party_id),
    CONSTRAINT fk_organization_parties_party FOREIGN KEY(tenant_id,party_id) REFERENCES public.parties(tenant_id,id) ON DELETE RESTRICT,
    CONSTRAINT ck_organization_parties_name CHECK(length(btrim(legal_name))>0)
