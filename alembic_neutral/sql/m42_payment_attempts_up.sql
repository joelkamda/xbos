    ADD COLUMN retry_of_attempt_id BIGINT NULL,
    ADD COLUMN timeout_at TIMESTAMPTZ NULL,
    ADD COLUMN terminal_at TIMESTAMPTZ NULL,
    ADD COLUMN failure_code VARCHAR(120) NULL;

ALTER TABLE public.canonical_payment_attempts
    ADD CONSTRAINT fk_canonical_payment_attempts_retry
        FOREIGN KEY (tenant_id, retry_of_attempt_id)
        REFERENCES public.canonical_payment_attempts(tenant_id, id) ON DELETE RESTRICT,
    ADD CONSTRAINT ck_canonical_payment_attempts_timeout
        CHECK (timeout_at IS NULL OR timeout_at > occurred_at),
    ADD CONSTRAINT ck_canonical_payment_attempts_terminal
        CHECK (
            (attempt_state IN ('succeeded','failed','cancelled','expired')) = (terminal_at IS NOT NULL)
        ),
    ADD CONSTRAINT ck_canonical_payment_attempts_failure
        CHECK (
            (attempt_state = 'failed' AND failure_code IS NOT NULL AND length(btrim(failure_code)) > 0)
            OR (attempt_state <> 'failed' AND failure_code IS NULL)
        );

