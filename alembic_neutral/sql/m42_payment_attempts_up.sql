CREATE OR REPLACE FUNCTION public.xbos_validate_payment_attempt_insert()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    prior public.canonical_payment_attempts;
BEGIN
    IF NEW.retry_of_attempt_id IS NULL THEN
        RETURN NEW;
    END IF;
    SELECT * INTO prior
    FROM public.canonical_payment_attempts
    WHERE tenant_id = NEW.tenant_id AND id = NEW.retry_of_attempt_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING MESSAGE = 'retry attempt authority does not exist';
    END IF;
    IF prior.id = NEW.id
       OR prior.payment_intent_id <> NEW.payment_intent_id
       OR prior.organization_unit_id <> NEW.organization_unit_id
       OR prior.currency_code <> NEW.currency_code
       OR prior.attempt_state NOT IN ('failed','cancelled','expired') THEN
        RAISE EXCEPTION USING MESSAGE = 'retry must follow a terminal unsuccessful attempt for the same intent';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.xbos_validate_payment_attempt_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    attempt public.canonical_payment_attempts;
    expected_sequence INTEGER;
BEGIN
    SELECT * INTO attempt
    FROM public.canonical_payment_attempts
    WHERE tenant_id = NEW.tenant_id AND id = NEW.payment_attempt_id
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING MESSAGE = 'payment attempt transition target does not exist';
    END IF;
    SELECT COALESCE(MAX(sequence_number), 0) + 1 INTO expected_sequence
    FROM public.canonical_payment_attempt_transitions
    WHERE tenant_id = NEW.tenant_id AND payment_attempt_id = NEW.payment_attempt_id;
    IF NEW.sequence_number <> expected_sequence THEN
        RAISE EXCEPTION USING MESSAGE = 'payment attempt transition sequence is not contiguous';
    END IF;
    IF expected_sequence = 1 THEN
        IF NEW.from_state IS NOT NULL OR NEW.to_state <> attempt.attempt_state THEN
            RAISE EXCEPTION USING MESSAGE = 'initial payment attempt transition is invalid';
        END IF;
        RETURN NEW;
    END IF;
    IF NEW.from_state IS DISTINCT FROM attempt.attempt_state THEN
        RAISE EXCEPTION USING MESSAGE = 'payment attempt transition source differs from current state';
    END IF;
    IF NOT (
        (attempt.attempt_state = 'pending' AND NEW.to_state IN ('processing','failed','cancelled','expired'))
        OR (attempt.attempt_state = 'processing' AND NEW.to_state IN ('requires_action','authorized','succeeded','failed','cancelled','expired'))
        OR (attempt.attempt_state = 'requires_action' AND NEW.to_state IN ('processing','authorized','succeeded','failed','cancelled','expired'))
        OR (attempt.attempt_state = 'authorized' AND NEW.to_state IN ('succeeded','failed','cancelled','expired'))
    ) THEN
        RAISE EXCEPTION USING MESSAGE = 'invalid payment attempt state transition';
    END IF;
    IF NEW.to_state = 'expired'
       AND (attempt.timeout_at IS NULL OR NEW.occurred_at < attempt.timeout_at) THEN
        RAISE EXCEPTION USING MESSAGE = 'payment attempt cannot expire before its timeout authority';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.xbos_capture_initial_payment_attempt_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO public.canonical_payment_attempt_transitions (
        tenant_id, organization_unit_id, payment_attempt_id, sequence_number,
        from_state, to_state, reason_code, external_attempt_reference_snapshot,
        evidence_payload, occurred_at, business_date, calendar_policy_version,
        correlation_id, actor_user_id, actor_service,
        source_component, source_record_id, metadata
    ) VALUES (
        NEW.tenant_id, NEW.organization_unit_id, NEW.id, 1,
        NULL, NEW.attempt_state, 'attempt_created', NEW.external_attempt_reference,
        '{}'::jsonb, NEW.occurred_at, NEW.business_date, NEW.calendar_policy_version,
        NEW.correlation_id, NEW.actor_user_id, NEW.actor_service,
        NEW.source_component, NEW.source_record_id || '.initial', '{}'::jsonb
    );
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.xbos_guard_payment_attempt_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    latest public.canonical_payment_attempt_transitions;
BEGIN
    IF NEW.tenant_id <> OLD.tenant_id
       OR NEW.organization_unit_id <> OLD.organization_unit_id
       OR NEW.payment_intent_id <> OLD.payment_intent_id
       OR NEW.payment_tender_id IS DISTINCT FROM OLD.payment_tender_id
       OR NEW.provider_account_id IS DISTINCT FROM OLD.provider_account_id
       OR NEW.retry_of_attempt_id IS DISTINCT FROM OLD.retry_of_attempt_id
       OR NEW.attempted_amount <> OLD.attempted_amount
       OR NEW.currency_code <> OLD.currency_code
       OR NEW.payment_method_code <> OLD.payment_method_code
       OR NEW.payment_rail_code <> OLD.payment_rail_code
       OR NEW.orchestrator_code <> OLD.orchestrator_code
       OR NEW.underlying_provider_code IS DISTINCT FROM OLD.underlying_provider_code
       OR NEW.timeout_at IS DISTINCT FROM OLD.timeout_at
       OR NEW.occurred_at <> OLD.occurred_at
       OR NEW.business_date <> OLD.business_date
       OR NEW.correlation_id <> OLD.correlation_id
       OR NEW.source_component <> OLD.source_component
       OR NEW.source_record_id <> OLD.source_record_id
       OR NEW.idempotency_scope <> OLD.idempotency_scope
       OR NEW.idempotency_key <> OLD.idempotency_key
       OR NEW.request_fingerprint <> OLD.request_fingerprint
       OR NEW.public_id <> OLD.public_id
       OR NEW.recorded_at <> OLD.recorded_at
       OR NEW.calendar_policy_version <> OLD.calendar_policy_version
       OR NEW.actor_user_id IS DISTINCT FROM OLD.actor_user_id
       OR NEW.actor_service IS DISTINCT FROM OLD.actor_service
       OR NEW.metadata IS DISTINCT FROM OLD.metadata
       OR NEW.created_at <> OLD.created_at THEN
        RAISE EXCEPTION USING MESSAGE = 'payment attempt identity and routing fields are immutable';
    END IF;
    IF NEW.attempt_state = OLD.attempt_state OR NEW.row_version <> OLD.row_version + 1 THEN
        RAISE EXCEPTION USING MESSAGE = 'payment attempt update requires one governed state transition';
    END IF;
    SELECT * INTO latest
    FROM public.canonical_payment_attempt_transitions
    WHERE tenant_id = OLD.tenant_id AND payment_attempt_id = OLD.id
    ORDER BY sequence_number DESC LIMIT 1;
    IF latest.from_state IS DISTINCT FROM OLD.attempt_state
       OR latest.to_state IS DISTINCT FROM NEW.attempt_state
       OR latest.external_attempt_reference_snapshot IS DISTINCT FROM NEW.external_attempt_reference
       OR latest.failure_code IS DISTINCT FROM NEW.failure_code THEN
        RAISE EXCEPTION USING MESSAGE = 'payment attempt update lacks matching append-only transition evidence';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.xbos_confirm_payment_attempt_history()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    current_state VARCHAR(32);
    latest_state VARCHAR(32);
BEGIN
    SELECT attempt_state INTO current_state
    FROM public.canonical_payment_attempts
    WHERE tenant_id = NEW.tenant_id AND id = NEW.payment_attempt_id;
    SELECT to_state INTO latest_state
    FROM public.canonical_payment_attempt_transitions
    WHERE tenant_id = NEW.tenant_id AND payment_attempt_id = NEW.payment_attempt_id
    ORDER BY sequence_number DESC LIMIT 1;
    IF current_state IS DISTINCT FROM latest_state THEN
        RAISE EXCEPTION USING MESSAGE = 'payment attempt state and append-only history diverge';
    END IF;
    RETURN NULL;
END;
$$;

