    ON public.canonical_payment_attempts
    (tenant_id, orchestrator_code, external_attempt_reference)
    WHERE provider_account_id IS NULL AND external_attempt_reference IS NOT NULL;

CREATE TABLE public.canonical_payment_attempt_transitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    tenant_id INTEGER NOT NULL,
    organization_unit_id BIGINT NOT NULL,
    payment_attempt_id BIGINT NOT NULL,
    sequence_number INTEGER NOT NULL,
    from_state VARCHAR(32) NULL,
    to_state VARCHAR(32) NOT NULL,
    reason_code VARCHAR(80) NOT NULL,
    failure_code VARCHAR(120) NULL,
    external_attempt_reference_snapshot VARCHAR(255) NULL,
    evidence_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    business_date DATE NOT NULL,
    calendar_policy_version INTEGER NOT NULL,
    correlation_id UUID NOT NULL,
    actor_user_id INTEGER NULL,
    actor_service VARCHAR(120) NULL,
    source_component VARCHAR(120) NOT NULL,
    source_record_id VARCHAR(200) NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_payment_attempt_transitions_public_id UNIQUE (public_id),
    CONSTRAINT uq_payment_attempt_transitions_sequence
        UNIQUE (tenant_id, payment_attempt_id, sequence_number),
    CONSTRAINT uq_payment_attempt_transitions_source
        UNIQUE (tenant_id, source_component, source_record_id),
    CONSTRAINT fk_payment_attempt_transitions_attempt FOREIGN KEY
        (tenant_id, organization_unit_id, payment_attempt_id)
        REFERENCES public.canonical_payment_attempts
        (tenant_id, organization_unit_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_payment_attempt_transitions_actor FOREIGN KEY
        (tenant_id, actor_user_id)
        REFERENCES public.users(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_payment_attempt_transitions_sequence CHECK (sequence_number > 0),
    CONSTRAINT ck_payment_attempt_transitions_from CHECK (
        from_state IS NULL OR from_state IN (
            'pending','processing','requires_action','authorized',
            'succeeded','failed','cancelled','expired'
        )
    ),
    CONSTRAINT ck_payment_attempt_transitions_to CHECK (
        to_state IN (
            'pending','processing','requires_action','authorized',
            'succeeded','failed','cancelled','expired'
        )
    ),
    CONSTRAINT ck_payment_attempt_transitions_reason
        CHECK (reason_code ~ '^[a-z][a-z0-9_.-]{0,79}$'),
    CONSTRAINT ck_payment_attempt_transitions_failure CHECK (
        (to_state = 'failed' AND failure_code IS NOT NULL AND length(btrim(failure_code)) > 0)
        OR (to_state <> 'failed' AND failure_code IS NULL)
    ),
    CONSTRAINT ck_payment_attempt_transitions_evidence
        CHECK (jsonb_typeof(evidence_payload) = 'object'),
    CONSTRAINT ck_payment_attempt_transitions_calendar
        CHECK (calendar_policy_version > 0),
    CONSTRAINT ck_payment_attempt_transitions_actor CHECK (
        actor_user_id IS NOT NULL
        OR (actor_service IS NOT NULL AND length(btrim(actor_service)) > 0)
    ),
    CONSTRAINT ck_payment_attempt_transitions_metadata
        CHECK (jsonb_typeof(metadata) = 'object')
);

