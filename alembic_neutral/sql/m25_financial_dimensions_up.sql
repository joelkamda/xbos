CREATE OR REPLACE FUNCTION public.xbos_reject_dimension_configuration_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $body$
DECLARE
    old_row JSONB;
    new_row JSONB;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING MESSAGE =
            'financial dimension configuration is historical; deactivate or end-date it';
    END IF;
    old_row := to_jsonb(OLD);
    new_row := to_jsonb(NEW);
    IF old_row ->> 'tenant_id' IS DISTINCT FROM new_row ->> 'tenant_id'
       OR old_row ->> 'id' IS DISTINCT FROM new_row ->> 'id' THEN
        RAISE EXCEPTION USING MESSAGE =
            'financial dimension identity is immutable';
    END IF;
    IF TG_TABLE_NAME = 'financial_dimension_types' AND (
        old_row ->> 'dimension_code' IS DISTINCT FROM new_row ->> 'dimension_code' OR
        old_row ->> 'effective_from' IS DISTINCT FROM new_row ->> 'effective_from'
    ) THEN
        RAISE EXCEPTION USING MESSAGE =
            'financial dimension type identity is immutable';
    END IF;
    IF TG_TABLE_NAME = 'financial_dimension_values' AND (
        old_row ->> 'dimension_type_id' IS DISTINCT FROM new_row ->> 'dimension_type_id' OR
        old_row ->> 'value_code' IS DISTINCT FROM new_row ->> 'value_code' OR
        old_row ->> 'parent_value_id' IS DISTINCT FROM new_row ->> 'parent_value_id' OR
        old_row ->> 'effective_from' IS DISTINCT FROM new_row ->> 'effective_from'
    ) THEN
        RAISE EXCEPTION USING MESSAGE =
            'financial dimension value identity is immutable';
    END IF;
    IF TG_TABLE_NAME = 'posting_dimension_policies' AND (
        old_row ->> 'legal_entity_unit_id' IS DISTINCT FROM new_row ->> 'legal_entity_unit_id' OR
        old_row ->> 'posting_profile_code' IS DISTINCT FROM new_row ->> 'posting_profile_code' OR
        old_row ->> 'account_role' IS DISTINCT FROM new_row ->> 'account_role' OR
        old_row ->> 'dimension_type_id' IS DISTINCT FROM new_row ->> 'dimension_type_id' OR
        old_row ->> 'requirement' IS DISTINCT FROM new_row ->> 'requirement' OR
        old_row ->> 'default_dimension_value_id' IS DISTINCT FROM new_row ->> 'default_dimension_value_id' OR
        old_row ->> 'effective_from' IS DISTINCT FROM new_row ->> 'effective_from'
    ) THEN
        RAISE EXCEPTION USING MESSAGE =
            'posting dimension policy semantics are immutable';
    END IF;
    RETURN NEW;
END
$body$;

CREATE TRIGGER trg_financial_dimension_types_history
BEFORE UPDATE OR DELETE ON public.financial_dimension_types
FOR EACH ROW EXECUTE FUNCTION public.xbos_reject_dimension_configuration_mutation();

CREATE TRIGGER trg_financial_dimension_values_history
BEFORE UPDATE OR DELETE ON public.financial_dimension_values
FOR EACH ROW EXECUTE FUNCTION public.xbos_reject_dimension_configuration_mutation();

CREATE TRIGGER trg_posting_dimension_policies_history
BEFORE UPDATE OR DELETE ON public.posting_dimension_policies
FOR EACH ROW EXECUTE FUNCTION public.xbos_reject_dimension_configuration_mutation();
