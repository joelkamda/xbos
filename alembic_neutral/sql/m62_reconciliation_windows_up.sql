CREATE OR REPLACE FUNCTION public.xbos_validate_reconciliation_revision_sequence()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE selected_window public.reconciliation_windows%ROWTYPE;
DECLARE latest public.reconciliation_window_revisions%ROWTYPE;
DECLARE selected_series public.reconciliation_series%ROWTYPE;
DECLARE selected_observation public.operational_account_balance_observations%ROWTYPE;
DECLARE selected_cascade public.reconciliation_cascade_runs%ROWTYPE;
BEGIN
    SELECT * INTO selected_window FROM public.reconciliation_windows
    WHERE tenant_id=NEW.tenant_id AND id=NEW.reconciliation_window_id FOR UPDATE;
    IF NOT FOUND OR selected_window.organization_unit_id<>NEW.organization_unit_id THEN
        RAISE EXCEPTION 'reconciliation revision window is missing or cross-scope' USING ERRCODE='23514';
    END IF;
    SELECT * INTO selected_series FROM public.reconciliation_series
    WHERE tenant_id=NEW.tenant_id AND id=selected_window.reconciliation_series_id;
    IF NEW.actual_observation_id IS NOT NULL THEN
        SELECT * INTO selected_observation FROM public.operational_account_balance_observations
        WHERE id=NEW.actual_observation_id;
        IF NOT FOUND OR selected_observation.tenant_id<>NEW.tenant_id
           OR selected_observation.operational_account_id<>selected_series.operational_account_id
           OR selected_observation.observed_at<=selected_window.window_start
           OR selected_observation.observed_at>selected_window.window_end THEN
            RAISE EXCEPTION 'reconciliation actual observation is outside the window account scope' USING ERRCODE='23514';
        END IF;
    END IF;
    IF NEW.cascade_run_id IS NOT NULL THEN
        SELECT * INTO selected_cascade FROM public.reconciliation_cascade_runs
        WHERE tenant_id=NEW.tenant_id AND id=NEW.cascade_run_id;
        IF NOT FOUND OR selected_cascade.reconciliation_series_id<>selected_window.reconciliation_series_id THEN
            RAISE EXCEPTION 'reconciliation revision cascade run belongs to another series' USING ERRCODE='23514';
        END IF;
    END IF;
    SELECT * INTO latest FROM public.reconciliation_window_revisions
    WHERE tenant_id=NEW.tenant_id AND reconciliation_window_id=NEW.reconciliation_window_id
    ORDER BY revision_number DESC,id DESC LIMIT 1 FOR UPDATE;
    IF NOT FOUND THEN
        IF NEW.revision_number<>1 OR NEW.supersedes_revision_id IS NOT NULL OR NEW.cascade_run_id IS NOT NULL THEN
            RAISE EXCEPTION 'first reconciliation revision must be revision one' USING ERRCODE='23514';
        END IF;
    ELSIF NEW.revision_number<>latest.revision_number+1 OR NEW.supersedes_revision_id IS DISTINCT FROM latest.id
          OR NEW.cascade_run_id IS NULL THEN
        RAISE EXCEPTION 'reconciliation revisions must append in order and supersede the latest revision' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;

