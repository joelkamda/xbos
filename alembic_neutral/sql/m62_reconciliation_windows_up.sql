CREATE OR REPLACE FUNCTION public.xbos_validate_reconciliation_calendar_policy()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE selected_boundary TEXT;
BEGIN
    IF NOT EXISTS(SELECT 1 FROM pg_timezone_names WHERE name=NEW.timezone_name) THEN
        RAISE EXCEPTION 'reconciliation calendar timezone is unknown' USING ERRCODE='23514';
    END IF;
    IF EXISTS(SELECT 1 FROM jsonb_array_elements(NEW.shift_definitions) item
              WHERE NULLIF(btrim(item->>'code'),'') IS NULL
                 OR NOT COALESCE((item->>'starts_at')~'^([01][0-9]|2[0-3]):[0-5][0-9]$',FALSE)) THEN
        RAISE EXCEPTION 'reconciliation shift definitions are invalid' USING ERRCODE='23514';
    END IF;
    IF (SELECT count(*) FROM jsonb_array_elements(NEW.shift_definitions))
       <> (SELECT count(DISTINCT item->>'code') FROM jsonb_array_elements(NEW.shift_definitions) item)
       OR (SELECT count(*) FROM jsonb_array_elements(NEW.shift_definitions))
       <> (SELECT count(DISTINCT item->>'starts_at') FROM jsonb_array_elements(NEW.shift_definitions) item) THEN
        RAISE EXCEPTION 'reconciliation shift codes and boundaries must be unique' USING ERRCODE='23514';
    END IF;
    selected_boundary := to_char(NEW.business_day_boundary,'HH24:MI');
    IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements(NEW.shift_definitions) item
                  WHERE item->>'starts_at'=selected_boundary) THEN
        RAISE EXCEPTION 'business-day boundary must begin a reconciliation shift' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION public.xbos_validate_reconciliation_series()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE selected_account public.operational_financial_accounts%ROWTYPE;
DECLARE selected_policy public.reconciliation_calendar_policies%ROWTYPE;
DECLARE local_start TEXT;
BEGIN
    SELECT * INTO selected_account FROM public.operational_financial_accounts
    WHERE tenant_id=NEW.tenant_id AND id=NEW.operational_account_id FOR SHARE;
    SELECT * INTO selected_policy FROM public.reconciliation_calendar_policies
    WHERE tenant_id=NEW.tenant_id AND id=NEW.calendar_policy_id FOR SHARE;
    IF selected_account.id IS NULL OR selected_policy.id IS NULL
       OR selected_account.organization_unit_id<>NEW.organization_unit_id
       OR selected_policy.organization_unit_id<>NEW.organization_unit_id
       OR selected_account.currency_code<>NEW.currency_code
       OR selected_policy.policy_version<>NEW.calendar_policy_version
       OR NOT selected_account.active OR NOT selected_account.reconciliation_enabled
       OR selected_account.aggregation_role<>'leaf' THEN
        RAISE EXCEPTION 'reconciliation series account, policy, scope, or currency is invalid' USING ERRCODE='23514';
    END IF;
    local_start := to_char(NEW.starts_at AT TIME ZONE selected_policy.timezone_name,'HH24:MI');
    IF NEW.starts_at<selected_account.opened_at OR NEW.starts_at<selected_policy.effective_from
       OR NOT EXISTS(SELECT 1 FROM jsonb_array_elements(selected_policy.shift_definitions) item
                     WHERE item->>'starts_at'=local_start) THEN
        RAISE EXCEPTION 'reconciliation series start is outside authority or not shift-aligned' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION public.xbos_validate_reconciliation_window_continuity()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE selected_series public.reconciliation_series%ROWTYPE;
DECLARE latest public.reconciliation_windows%ROWTYPE;
DECLARE selected_policy public.reconciliation_calendar_policies%ROWTYPE;
DECLARE local_start TIMESTAMP;
DECLARE local_clock TEXT;
DECLARE selected_shift TEXT;
DECLARE next_clock TIME;
DECLARE next_day INTEGER;
DECLARE expected_end TIMESTAMPTZ;
DECLARE expected_business_date DATE;
BEGIN
    SELECT * INTO selected_series FROM public.reconciliation_series
    WHERE tenant_id=NEW.tenant_id AND id=NEW.reconciliation_series_id FOR UPDATE;
    IF NOT FOUND OR selected_series.organization_unit_id<>NEW.organization_unit_id THEN
        RAISE EXCEPTION 'reconciliation window series is missing or cross-scope' USING ERRCODE='23514';
    END IF;
    SELECT * INTO selected_policy FROM public.reconciliation_calendar_policies
    WHERE tenant_id=NEW.tenant_id AND id=selected_series.calendar_policy_id;
    IF selected_policy.policy_version<>NEW.calendar_policy_version THEN
        RAISE EXCEPTION 'reconciliation window calendar version differs from series policy' USING ERRCODE='23514';
    END IF;
    local_start := NEW.window_start AT TIME ZONE selected_policy.timezone_name;
    local_clock := to_char(local_start,'HH24:MI');
    SELECT item->>'code' INTO selected_shift FROM jsonb_array_elements(selected_policy.shift_definitions) item
    WHERE item->>'starts_at'=local_clock;
    IF selected_shift IS NULL THEN
        RAISE EXCEPTION 'reconciliation window start is not a configured shift boundary' USING ERRCODE='23514';
    END IF;
    SELECT min((item->>'starts_at')::TIME) INTO next_clock
    FROM jsonb_array_elements(selected_policy.shift_definitions) item
    WHERE (item->>'starts_at')::TIME>local_clock::TIME;
    next_day := 0;
    IF next_clock IS NULL THEN
        SELECT min((item->>'starts_at')::TIME) INTO next_clock FROM jsonb_array_elements(selected_policy.shift_definitions) item;
        next_day := 1;
    END IF;
    expected_end := ((local_start::DATE+next_day)+next_clock) AT TIME ZONE selected_policy.timezone_name;
    expected_business_date := local_start::DATE;
    IF local_clock::TIME<selected_policy.business_day_boundary THEN
        expected_business_date := expected_business_date-1;
    END IF;
    IF NEW.window_end<>expected_end OR NEW.shift_code<>selected_shift OR NEW.business_date<>expected_business_date THEN
        RAISE EXCEPTION 'reconciliation window end, shift, or business date conflicts with calendar authority' USING ERRCODE='23514';
    END IF;
    SELECT * INTO latest FROM public.reconciliation_windows
    WHERE tenant_id=NEW.tenant_id AND reconciliation_series_id=NEW.reconciliation_series_id
    ORDER BY window_start DESC,id DESC LIMIT 1 FOR UPDATE;
    IF NOT FOUND THEN
        IF NEW.predecessor_window_id IS NOT NULL OR NEW.window_start<>selected_series.starts_at THEN
            RAISE EXCEPTION 'first reconciliation window must start the series without a predecessor' USING ERRCODE='23514';
        END IF;
    ELSIF NEW.predecessor_window_id IS DISTINCT FROM latest.id OR NEW.window_start<>latest.window_end THEN
        RAISE EXCEPTION 'reconciliation windows must be contiguous and name the latest predecessor' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;

