CREATE VIEW public.current_reconciliation_window_revisions AS
SELECT DISTINCT ON (r.tenant_id,r.reconciliation_window_id)
       r.*,w.reconciliation_series_id,w.predecessor_window_id,w.window_start,w.window_end,w.business_date,w.shift_code,
       o.observed_at AS actual_observed_at,o.provenance AS actual_provenance,o.evidence_hash AS actual_evidence_hash
FROM public.reconciliation_window_revisions r
JOIN public.reconciliation_windows w ON w.tenant_id=r.tenant_id AND w.id=r.reconciliation_window_id
LEFT JOIN public.operational_account_balance_observations o ON o.id=r.actual_observation_id
ORDER BY r.tenant_id,r.reconciliation_window_id,r.revision_number DESC,r.id DESC;
