CREATE OR REPLACE FUNCTION public.xbos_reject_obligation_fact_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $body$
BEGIN
    RAISE EXCEPTION USING
        ERRCODE = '55000',
        MESSAGE = TG_TABLE_NAME || ' is immutable; append a compensating fact instead';
END
$body$;

CREATE OR REPLACE FUNCTION public.xbos_validate_payment_allocation_scope()
RETURNS trigger
LANGUAGE plpgsql
AS $body$
DECLARE
    source_org_id BIGINT;
    obligation_org_id BIGINT;
BEGIN
    SELECT organization_unit_id INTO source_org_id
    FROM public.value_sources
    WHERE tenant_id = NEW.tenant_id AND id = NEW.value_source_id;

    SELECT organization_unit_id INTO obligation_org_id
    FROM public.financial_obligations
    WHERE tenant_id = NEW.tenant_id AND id = NEW.obligation_id;

    IF obligation_org_id IS NOT NULL
       AND NEW.organization_unit_id <> obligation_org_id THEN
        RAISE EXCEPTION USING
            ERRCODE = '23514',
            MESSAGE = 'allocation organization must be the obligation organization';
    END IF;

    IF source_org_id IS NOT NULL AND obligation_org_id IS NOT NULL THEN
        IF source_org_id <> obligation_org_id
           AND NEW.cross_organization_policy_code IS NULL THEN
            RAISE EXCEPTION USING
                ERRCODE = '23514',
                MESSAGE = 'cross-organization allocation requires explicit policy';
        END IF;
        IF source_org_id = obligation_org_id
           AND NEW.cross_organization_policy_code IS NOT NULL THEN
            RAISE EXCEPTION USING
                ERRCODE = '23514',
                MESSAGE = 'cross-organization policy is invalid for same-organization allocation';
        END IF;
    END IF;
    RETURN NEW;
END
$body$;

CREATE OR REPLACE FUNCTION public.xbos_protect_financial_obligation_authority()
RETURNS trigger
LANGUAGE plpgsql
AS $body$
BEGIN
    IF OLD.public_id IS DISTINCT FROM NEW.public_id
       OR OLD.tenant_id IS DISTINCT FROM NEW.tenant_id
       OR OLD.organization_unit_id IS DISTINCT FROM NEW.organization_unit_id
       OR OLD.debtor_party_id IS DISTINCT FROM NEW.debtor_party_id
       OR OLD.creditor_party_id IS DISTINCT FROM NEW.creditor_party_id
       OR OLD.commercial_transaction_public_id IS DISTINCT FROM NEW.commercial_transaction_public_id
       OR OLD.obligation_type IS DISTINCT FROM NEW.obligation_type
       OR OLD.original_amount IS DISTINCT FROM NEW.original_amount
       OR OLD.currency_code IS DISTINCT FROM NEW.currency_code
       OR OLD.due_at IS DISTINCT FROM NEW.due_at
       OR OLD.occurred_at IS DISTINCT FROM NEW.occurred_at
       OR OLD.recorded_at IS DISTINCT FROM NEW.recorded_at
       OR OLD.business_date IS DISTINCT FROM NEW.business_date
       OR OLD.calendar_policy_version IS DISTINCT FROM NEW.calendar_policy_version
       OR OLD.correlation_id IS DISTINCT FROM NEW.correlation_id
       OR OLD.actor_user_id IS DISTINCT FROM NEW.actor_user_id
       OR OLD.actor_service IS DISTINCT FROM NEW.actor_service
       OR OLD.source_component IS DISTINCT FROM NEW.source_component
       OR OLD.source_record_id IS DISTINCT FROM NEW.source_record_id
       OR OLD.idempotency_scope IS DISTINCT FROM NEW.idempotency_scope
       OR OLD.idempotency_key IS DISTINCT FROM NEW.idempotency_key
       OR OLD.request_fingerprint IS DISTINCT FROM NEW.request_fingerprint
       OR OLD.metadata IS DISTINCT FROM NEW.metadata THEN
        RAISE EXCEPTION USING
            ERRCODE = '55000',
            MESSAGE = 'financial obligation authority is immutable';
    END IF;
    IF NEW.row_version <> OLD.row_version + 1 THEN
        RAISE EXCEPTION USING
            ERRCODE = '23514',
            MESSAGE = 'financial obligation state change requires one row-version increment';
    END IF;
    NEW.updated_at := now();
    RETURN NEW;
END
$body$;

