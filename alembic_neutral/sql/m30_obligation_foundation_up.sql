CREATE TABLE public.financial_obligations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    tenant_id INTEGER NOT NULL,
    organization_unit_id BIGINT NOT NULL,
    debtor_party_id UUID NOT NULL,
    creditor_party_id UUID NOT NULL,
    commercial_transaction_public_id UUID NULL,
    obligation_type VARCHAR(64) NOT NULL,
    obligation_state VARCHAR(32) NOT NULL DEFAULT 'open',
    original_amount NUMERIC(24,8) NOT NULL,
    currency_code VARCHAR(3) NOT NULL,
    due_at TIMESTAMPTZ NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    business_date DATE NOT NULL,
    calendar_policy_version INTEGER NOT NULL,
    correlation_id UUID NOT NULL,
    actor_user_id INTEGER NULL,
    actor_service VARCHAR(120) NULL,
    source_component VARCHAR(120) NOT NULL,
    source_record_id VARCHAR(200) NOT NULL,
    idempotency_scope VARCHAR(80) NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL,
    request_fingerprint CHAR(64) NOT NULL,
    row_version INTEGER NOT NULL DEFAULT 1,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_financial_obligations_public_id UNIQUE (public_id),
    CONSTRAINT uq_financial_obligations_tenant_id_id UNIQUE (tenant_id, id),
    CONSTRAINT uq_financial_obligations_scope_key
        UNIQUE (tenant_id, idempotency_scope, idempotency_key),
    CONSTRAINT uq_financial_obligations_source_identity
        UNIQUE (tenant_id, source_component, source_record_id, obligation_type),
    CONSTRAINT uq_financial_obligations_line_target
        UNIQUE (tenant_id, organization_unit_id, id, currency_code),
    CONSTRAINT uq_financial_obligations_allocation_target
        UNIQUE (tenant_id, id, currency_code),
    CONSTRAINT fk_financial_obligations_tenant FOREIGN KEY (tenant_id)
        REFERENCES public.tenants(id) ON DELETE RESTRICT,
    CONSTRAINT fk_financial_obligations_org FOREIGN KEY
        (tenant_id, organization_unit_id)
        REFERENCES public.organization_units(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_financial_obligations_currency FOREIGN KEY (currency_code)
        REFERENCES public.currency_assets(code) ON DELETE RESTRICT,
    CONSTRAINT fk_financial_obligations_actor_user FOREIGN KEY
        (tenant_id, actor_user_id)
        REFERENCES public.users(tenant_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_financial_obligations_party_distinct
        CHECK (debtor_party_id <> creditor_party_id),
    CONSTRAINT ck_financial_obligations_amount CHECK (original_amount > 0),
    CONSTRAINT ck_financial_obligations_state CHECK (
        obligation_state IN (
            'open', 'partially_satisfied', 'satisfied', 'cancelled', 'written_off'
        )
    ),
    CONSTRAINT ck_financial_obligations_type
        CHECK (obligation_type ~ '^[a-z][a-z0-9_]{0,63}$'),
    CONSTRAINT ck_financial_obligations_calendar_version
        CHECK (calendar_policy_version > 0),
    CONSTRAINT ck_financial_obligations_row_version CHECK (row_version > 0),
    CONSTRAINT ck_financial_obligations_actor CHECK (
        actor_user_id IS NOT NULL
        OR (actor_service IS NOT NULL AND length(btrim(actor_service)) > 0)
    ),
    CONSTRAINT ck_financial_obligations_fingerprint
        CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_financial_obligations_metadata
        CHECK (jsonb_typeof(metadata) = 'object')
);

