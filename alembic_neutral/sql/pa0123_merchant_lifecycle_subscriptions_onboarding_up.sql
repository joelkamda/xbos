CREATE TRIGGER trg_pa_plan_quota_immutable BEFORE UPDATE OR DELETE ON public.pa_plan_quotas FOR EACH ROW EXECUTE FUNCTION public.pa_reject_append_only_mutation();
CREATE TRIGGER trg_pa_subscription_history_immutable BEFORE UPDATE OR DELETE ON public.pa_subscription_history FOR EACH ROW EXECUTE FUNCTION public.pa_reject_append_only_mutation();
CREATE TRIGGER trg_pa_usage_immutable BEFORE UPDATE OR DELETE ON public.pa_usage_events FOR EACH ROW EXECUTE FUNCTION public.pa_reject_append_only_mutation();
CREATE TRIGGER trg_pa_onboarding_checks_immutable BEFORE UPDATE OR DELETE ON public.pa_onboarding_checks FOR EACH ROW EXECUTE FUNCTION public.pa_reject_append_only_mutation();

