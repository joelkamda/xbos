CREATE TABLE public.currency_assets (
    code VARCHAR(12) PRIMARY KEY,
    asset_kind VARCHAR(16) NOT NULL,
    display_name VARCHAR(80) NOT NULL,
    minor_unit_scale SMALLINT NOT NULL,
    maximum_storage_scale SMALLINT NOT NULL DEFAULT 8,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_currency_assets_kind
        CHECK (asset_kind IN ('fiat','crypto','points','other')),
    CONSTRAINT ck_currency_assets_code_upper
        CHECK (code = upper(btrim(code)) AND length(code) > 0),
    CONSTRAINT ck_currency_assets_minor_scale
        CHECK (minor_unit_scale BETWEEN 0 AND 8),
    CONSTRAINT ck_currency_assets_max_scale
        CHECK (maximum_storage_scale BETWEEN minor_unit_scale AND 8),
    CONSTRAINT ck_currency_assets_metadata_object
        CHECK (jsonb_typeof(metadata) = 'object')
);

