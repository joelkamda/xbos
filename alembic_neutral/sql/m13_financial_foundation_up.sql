CREATE OR REPLACE FUNCTION public.xbos_reject_immutable_financial_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION '% is immutable; append a correcting fact instead', TG_TABLE_NAME
        USING ERRCODE = '55000';
END
$$;

CREATE OR REPLACE FUNCTION public.xbos_validate_financial_event_amount()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    selected_policy VARCHAR(24);
BEGIN
    SELECT amount_policy INTO selected_policy
    FROM public.financial_event_type_versions
    WHERE event_type_code = NEW.event_type_code
      AND event_version = NEW.event_version;

    IF selected_policy = 'positive' AND NEW.amount <= 0 THEN
        RAISE EXCEPTION 'event amount must be positive for % v%', NEW.event_type_code, NEW.event_version
            USING ERRCODE = '23514';
    ELSIF selected_policy = 'nonzero' AND NEW.amount = 0 THEN
        RAISE EXCEPTION 'event amount must be nonzero for % v%', NEW.event_type_code, NEW.event_version
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END
$$;

CREATE OR REPLACE FUNCTION public.xbos_protect_outbox_content()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF ROW(
        NEW.public_id, NEW.tenant_id, NEW.source_event_public_id,
        NEW.aggregate_type, NEW.aggregate_public_id, NEW.event_name,
        NEW.event_version, NEW.payload, NEW.payload_hash,
        NEW.created_at, NEW.correlation_id, NEW.causation_id
    ) IS DISTINCT FROM ROW(
        OLD.public_id, OLD.tenant_id, OLD.source_event_public_id,
        OLD.aggregate_type, OLD.aggregate_public_id, OLD.event_name,
        OLD.event_version, OLD.payload, OLD.payload_hash,
        OLD.created_at, OLD.correlation_id, OLD.causation_id
    ) THEN
        RAISE EXCEPTION 'outbox message content and identity are immutable'
            USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END
$$;

